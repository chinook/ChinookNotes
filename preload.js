const { contextBridge, ipcRenderer, webFrame } = require('electron');

contextBridge.exposeInMainWorld('api', {
    listePages: () => ipcRenderer.invoke('pages:liste'),
    listeModeles: () => ipcRenderer.invoke('modeles:liste'),
    creerModele: (modele) => ipcRenderer.invoke('modeles:creer', modele),
    supprimerModele: (id) => ipcRenderer.invoke('modeles:supprimer', id),
    pagesRecentes: () => ipcRenderer.invoke('pages:recentes'),
    rechercher: (requete) => ipcRenderer.invoke('pages:rechercher', requete),
    mettreALaCorbeille: (id) => ipcRenderer.invoke('pages:corbeille', id),
    listeCorbeille: () => ipcRenderer.invoke('pages:corbeille-liste'),
    restaurerPage: (id) => ipcRenderer.invoke('pages:restaurer', id),
    viderCorbeille: () => ipcRenderer.invoke('pages:vider-corbeille'),
    dupliquerPage: (id, parentId) => ipcRenderer.invoke('pages:dupliquer', id, parentId),
    lireReglages: () => ipcRenderer.invoke('reglages:lire'),
    ecrireReglage: (cle, valeur) => ipcRenderer.invoke('reglages:ecrire', cle, valeur),
    listeEmojis: () => ipcRenderer.invoke('emojis:liste'),
    creerEmoji: (emoji) => ipcRenderer.invoke('emojis:creer', emoji),
    supprimerEmoji: (id) => ipcRenderer.invoke('emojis:supprimer', id),
    statsProfil: () => ipcRenderer.invoke('profil:stats'),
    definirZoom: (facteur) => webFrame.setZoomFactor(facteur),
    lireZoom: () => webFrame.getZoomFactor(),
    // « retour » / « avance » : boutons latéraux de la souris (commande système de Windows)
    surNavigation: (rappel) => ipcRenderer.on('nav', (event, sens) => rappel(sens)),
    themeFenetre: (theme) => ipcRenderer.invoke('fenetre:theme', theme),
    actionFenetre: (action) => ipcRenderer.invoke('fenetre:action', action),
    menuContextuel: (modele) => ipcRenderer.invoke('menu:popup', modele),
    lirePage: (id) => ipcRenderer.invoke('pages:lire', id),
    creerPage: (parentId, titre) => ipcRenderer.invoke('pages:creer', parentId, titre),
    creerBase: (parentId, titre, icone, schema) => ipcRenderer.invoke('pages:creer-base', parentId, titre, icone, schema),
    modifierPage: (id, champs) => ipcRenderer.invoke('pages:modifier', id, champs),
    deplacerPage: (id, parentId, position) => ipcRenderer.invoke('pages:deplacer', id, parentId, position),
    supprimerPage: (id) => ipcRenderer.invoke('pages:supprimer', id),
    lireDossierImport: () => ipcRenderer.invoke('import:lire-dossier'),
    choisirDestination: (options) => ipcRenderer.invoke('export:choisir', options),
    ecrireFichiers: (racine, fichiers) => ipcRenderer.invoke('export:ecrire', racine, fichiers),
    exporterPdf: (html, chemin) => ipcRenderer.invoke('export:pdf', html, chemin),
    afficherDansDossier: (chemin) => ipcRenderer.invoke('export:afficher', chemin),
    importerPages: (liste) => ipcRenderer.invoke('import:pages', liste),
});
